//! Cryptographic hashing.
//!
//! SHA-256 per FIPS 180-4, HMAC per RFC 2104. Implemented in-tree so the
//! deploying organisation can audit every byte of the evidence-integrity path
//! without trusting an external supply chain.
//!
//! Covered by the published NIST test vectors in the unit tests below.

